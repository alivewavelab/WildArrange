/**
 * 从混合数组中提取非空字符串并去重，保持首次出现顺序。
 * @param {unknown[]} values 待过滤的原始值列表
 * @returns {string[]} 去重后的字符串数组
 */
export function uniqueStrings(values) {
  return [...new Set(values.filter((value) => typeof value === "string" && value.length > 0))];
}
